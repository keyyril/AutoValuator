with tab4:
    st.subheader("Data Explorer")
    st.write("Browse, filter, and sort the cleaned auction dataset.")

    ec1, ec2, ec3 = st.columns(3)
    with ec1:
        flt_make  = st.multiselect("Make",         sorted(df["make"].dropna().unique()),               key="exp_make")
